import resend
import os
from dotenv import load_dotenv

load_dotenv()

resend.api_key = os.getenv("RESEND_API_KEY")

# This is the sender address
# On free tier Resend gives you onboarding@resend.dev
# You can use this until you connect a custom domain
SENDER_EMAIL = "onboarding@resend.dev"
SENDER_NAME = "LoanWise AI"


def send_loan_email(
    applicant_email: str,
    applicant_name: str,
    decision: str,
    email_body: str
) -> dict:
    """
    Sends the generated loan decision email to the applicant.

    Parameters:
        applicant_email : recipient's email address
        applicant_name  : recipient's name for the subject line
        decision        : APPROVED or DENIED
        email_body      : the full email text from email_agent.py

    Returns:
        dict with send status and message ID
    """
    subject = (
        f"Your Loan Application Has Been {decision.capitalize()} — LoanWise AI"
    )

    # Convert plain text to basic HTML for better email rendering
    html_body = email_body.replace("\n", "<br>")
    html_body = f"""
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px;">
        <div style="background: #1a1a2e; padding: 20px; border-radius: 8px; margin-bottom: 20px;">
            <h1 style="color: #4a9eff; margin: 0; font-size: 24px;">LoanWise AI</h1>
            <p style="color: #888; margin: 5px 0 0 0; font-size: 14px;">Intelligent Loan Approval System</p>
        </div>
        <div style="background: #f9f9f9; padding: 20px; border-radius: 8px; line-height: 1.6;">
            {html_body}
        </div>
        <div style="margin-top: 20px; padding: 15px; background: #f0f0f0; border-radius: 8px; font-size: 12px; color: #666;">
            This email was generated by LoanWise AI. Please do not reply to this email.
        </div>
    </div>
    """

    try:
        response = resend.Emails.send({
            "from": f"{SENDER_NAME} <{SENDER_EMAIL}>",
            "to": [applicant_email],
            "subject": subject,
            "html": html_body
        })

        return {
            "sent": True,
            "message_id": response.get("id"),
            "recipient": applicant_email,
            "error": None
        }

    except Exception as e:
        print(f"Email send failed: {e}")
        return {
            "sent": False,
            "message_id": None,
            "recipient": applicant_email,
            "error": str(e)
        }